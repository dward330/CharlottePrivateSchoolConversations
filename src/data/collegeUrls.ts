// Every college name rendered on a school's "Where Graduates Go" acceptance list
// resolves its homepage link from THIS file, so a URL lives in exactly one place
// and a correction updates all 11 schools at once. Acceptance-list data files
// carry only { name, cats } — never an inline url. Look one up with urlFor(name).
//
// Human-readable companion (with a verification per URL) lives at
// source-material/college-support/_shared/College Homepages 2026.md and is kept
// in sync with this file (npm run check:collegeurls).
//
// A college with no resolvable homepage — defunct, merged away, a campus with no
// distinct site, non-degree, or a name too ambiguous to resolve — is simply
// ABSENT here: urlFor returns undefined and the name renders as plain text, the
// way every row did before the links existed. That is a confirmed result, not a
// gap to be filled later, so check:collegeurls deliberately does NOT gate on
// coverage; it prints the linked/unlinked counts and exits 0. Never guess a URL
// to fill a row — a wrong link sends a parent to the wrong institution.
//
// Keys are the college names EXACTLY as the school lists write them, because
// that is what urlFor() is handed. The same institution therefore appears under
// several spellings (26 University of California variants, the UNC-system
// campus-tag forms) and two rows carry a misspelling the school published
// ("Clafin University", "Deleware State University") — those resolve to the
// institution actually meant. Names are not corrected here; the acceptance list
// is a citation surface.
//
// Unlike collegeRankings.ts there is no separate ALIAS map: variant spellings
// are ordinary keys here, because this table is built FROM the names its
// consumers actually pass. There are TWO such consumers and they use different
// vocabularies for the same institution:
//
//   1. the "Where Graduates Go" acceptance lists, which spell an institution out
//      ("University of North Carolina at Chapel Hill"), and
//   2. the Top-6 NC publics card (ncAdmissions), which carries the UNC system
//      dashboard's own short form ("UNC-Chapel Hill") — those strings are fixed
//      by the dashboard's house style and must be copied verbatim, so they
//      cannot be normalized toward the acceptance-list spellings.
//
// normName() bridges punctuation and University/College/Saint abbreviation, but
// NOT initialisms, so "UNC-Chapel Hill" does not reach
// "University of North Carolina at Chapel Hill" on its own. The six dashboard
// spellings are therefore listed explicitly at the end of the table, pointing at
// the same URLs. Adding a seventh campus to that card means adding its
// dashboard spelling here too, or its row renders unlinked.

