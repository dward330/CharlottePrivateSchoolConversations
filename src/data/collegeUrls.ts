// Build the normalized lookup once from the canonical table, mirroring
// collegeRankings.ts. normName() is IMPORTED, never redefined — that file's
// comment requires one shared copy, and a third would drift.
const BY_NORM: Map<string, string> = new Map(
  Object.entries(COLLEGE_URLS).map(([name, url]) => [normName(name), url]),
)

/**
 * The official homepage for a college by any of its name spellings, or
 * undefined if none resolves (so the name should render as plain text).
 */
export function urlFor(name: string): string | undefined {
  return BY_NORM.get(normName(name))
}
