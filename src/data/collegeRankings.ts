/**
 * Normalize a college name to its lookup key: lowercase, apostrophes removed,
 * "and"->"&", dashes/punctuation flattened, University/College/Saint
 * abbreviated. Matches institutions across the many spellings the acceptance
 * lists use ("University of California–Irvine" == "UC (Irvine)").
 */
function normName(s: string): string {
  return s
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/\band\b/g, '&')
    .replace(/[–—-]/g, ' ')
    .replace(/[().,]/g, ' ')
    .replace(/\buniversity\b/g, 'univ')
    .replace(/\bcollege\b/g, 'coll')
    .replace(/\bsaint\b/g, 'st')
    .replace(/\bthe\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

// Build the normalized lookup once from the canonical table.
const BY_NORM: Map<string, string> = new Map(
  Object.entries(COLLEGE_RANKINGS).map(([name, label]) => [normName(name), label]),
)

// Cross-name aliases: a bare flagship name or campus-tagged variant that a list
// may use, mapped to the canonical institution already in the table. Branch
// campuses that are their OWN (unranked/Regional) institution are deliberately
// NOT aliased — e.g. University of Pittsburgh (Bradford) stays unlabeled.
const ALIAS: Record<string, string> = {
  'univ of illinois': 'University of Illinois Urbana-Champaign',
  'univ of massachusetts': 'University of Massachusetts Amherst',
  'univ of hawaii': 'University of Hawaii at Manoa',
  'univ of tennessee': 'The University of Tennessee, Knoxville',
  'penn state univ': 'Penn State University (University Park)',
  'purdue univ main campus': 'Purdue University',
  // Sewanee appears with the "Sewanee" tag before, after, or absent — all one school.
  'univ of south': 'Sewanee: The University of the South',
  'univ of south sewanee': 'Sewanee: The University of the South',
  // Spelling variants a list may use for a school already in the table.
  'florida agricultural & mechanical': 'Florida A&M University',
  'indiana univ at bloomington': 'Indiana University (Bloomington)',
  'lynchburg coll': 'University of Lynchburg',
  'st johns univ queens campus': "St. John's University",
  'univ of alabama tuscaloosa': 'The University of Alabama',
}
for (const [variant, canon] of Object.entries(ALIAS)) {
  const label = BY_NORM.get(normName(canon))
  if (label) BY_NORM.set(normName(variant), label)
}

/**
 * The US News rank label for a college by any of its name spellings, or
 * undefined if it holds no National/LAC rank (so no label should render).
 */
export function rankLabelFor(name: string): string | undefined {
  return BY_NORM.get(normName(name))
}
